import { test, expect } from '@playwright/test';
test('desktop renders 3D, selects agents, completes work and retains results', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('Đã kết nối', { exact: true })).toBeVisible();
  await expect(page.locator('canvas')).toBeVisible();
  await expect(page.locator('.scene-name')).toHaveCount(3);
  await expect(page.getByRole('button', { name: 'Chọn Linh', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Chọn Linh', exact: true }).click();
  await expect(page.locator('.agent-detail')).toContainText('Linh · Phân tích');
  await page.getByRole('button', { name: 'Đặt lại góc nhìn' }).click();
  const prompt = `Lên kế hoạch cho quán cà phê sách ${Date.now()}`;
  await page.getByLabel('Công việc của bạn', { exact: true }).fill(prompt);
  await page.getByRole('button', { name: 'Bắt đầu cùng đội ngũ' }).click();
  const row = page.locator('.job-row').filter({ hasText: prompt });
  await expect(row.getByText('Hoàn thành', { exact: true })).toBeVisible({ timeout: 15000 });
  await expect(row.locator('article')).toHaveCount(3);
  await expect(row.locator('article').last()).toContainText('[Mô phỏng]');
  const downloadPromise = page.waitForEvent('download');
  await row.getByRole('button', { name: 'Tải kết quả' }).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/van-phong-ai-.*\.txt/);
  await page.screenshot({ path: '/tmp/van-phong-ai-desktop.png', fullPage: true });
  await page.reload();
  const restored = page.locator('.job-row').filter({ hasText: prompt });
  await expect(restored).toContainText('Hoàn thành');
  await restored.locator('.job-summary').click();
  await expect(restored.locator('article')).toHaveCount(3);
  await page.getByRole('button', { name: 'Khám phá văn phòng' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(errors).toEqual([]);
});
