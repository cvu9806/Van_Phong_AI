test('without WebGL, agent selection and work form remain usable', async ({ page }) => {
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(type: string, ...args: unknown[]) {
      if (type.includes('webgl')) return null;
      return original.apply(this, [type, ...args] as never);
    } as typeof original;
  });
  await page.goto('/');
  await expect(page.getByText('Đã kết nối', { exact: true })).toBeVisible();
  await expect(page.locator('.scene-fallback')).toBeVisible();
  await page.locator('.agent-card').filter({ hasText: 'An' }).click();
  await expect(page.locator('.agent-detail')).toContainText('An · Sáng tạo');
  await page.getByLabel('Công việc của bạn', { exact: true }).fill('Viết kế hoạch thử nghiệm khi không có WebGL');
  await expect(page.getByRole('button', { name: 'Bắt đầu cùng đội ngũ' })).toBeEnabled();
});
test('Codex mode displays login requirements and can refresh status', async ({ page, request }) => {
  const snapshot = await (await request.get('/api/office')).json();
  let ready = false;
  await page.route('**/api/events', route => route.fulfill({
    contentType: 'text/event-stream', body: `data: ${JSON.stringify({ ...snapshot, mode: 'live', provider: 'codex' })}\n\n`,
  }));
  await page.route('**/api/provider', route => route.fulfill({ json: { ready, provider: 'codex', message: ready ? 'Codex đã đăng nhập bằng ChatGPT.' : 'Chạy codex login trên máy chạy backend.' } }));
  await page.goto('/');
  await expect(page.locator('.mode-pill')).toHaveText('Codex CLI');
  await expect(page.locator('.provider-status')).toContainText('Chạy codex login');
  await page.getByLabel('Công việc của bạn', { exact: true }).fill('Viết nội dung với Codex CLI');
  await expect(page.getByRole('button', { name: 'Bắt đầu cùng đội ngũ' })).toBeDisabled();
  ready = true;
  await page.getByRole('button', { name: 'Kiểm tra lại kết nối' }).click();
  await expect(page.locator('.provider-status')).toContainText('Codex đã đăng nhập bằng ChatGPT.');
});
test('2D office persists and users can queue, cancel, retry and filter work', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByText('Đã kết nối', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Sơ đồ 2D', exact: true }).click();
  await expect(page.locator('.overview-desk')).toHaveCount(3);
  await page.locator('.overview-desk').filter({ hasText: 'Linh' }).click();
  await expect(page.locator('.agent-detail')).toContainText('Linh · Phân tích');
  await page.reload();
  await expect(page.locator('.office-overview')).toBeVisible();
  await expect(page.locator('canvas')).toHaveCount(0);
  const first = `Kế hoạch đầu tiên ${Date.now()}`;
  const second = `Nội dung hàng đợi ${Date.now()}`;
  await page.getByLabel('Công việc của bạn', { exact: true }).fill(first);
  await page.getByRole('button', { name: 'Bắt đầu cùng đội ngũ', exact: true }).click();
  await page.getByLabel('Công việc của bạn', { exact: true }).fill(second);
  await page.getByRole('button', { name: 'Thêm vào hàng đợi', exact: true }).click();
  const queued = page.locator('.job-row').filter({ hasText: second });
  await expect(queued).toContainText('Đang chờ');
  await queued.getByRole('button', { name: 'Hủy công việc', exact: true }).click();
  await expect(queued).toContainText('Đã hủy');
  await queued.getByRole('button', { name: 'Thử lại', exact: true }).click();
  const retried = page.locator('.job-row').filter({ hasText: second }).filter({ hasText: 'Lượt thử lại' });
  await expect(retried).toHaveCount(1);
  await expect(retried.locator('.job-status')).toHaveText('Hoàn thành', { timeout: 15000 });
  await expect(retried.locator('article')).toHaveCount(3);
  await expect(retried.locator('.job-stepper .done')).toHaveCount(3);
  await page.getByRole('searchbox', { name: 'Tìm công việc' }).fill(second);
  await expect(page.locator('.job-row')).toHaveCount(2);
  await page.getByRole('group', { name: 'Lọc công việc' }).getByRole('button', { name: 'Đã hủy' }).click();
  await expect(page.locator('.job-row')).toHaveCount(1);
  await page.getByRole('searchbox', { name: 'Tìm công việc' }).fill('không có công việc phù hợp');
  await expect(page.getByText('Không tìm thấy công việc phù hợp')).toBeVisible();
  await page.getByRole('button', { name: 'Xóa bộ lọc' }).click();
  await expect(page.locator('.job-row').filter({ hasText: second })).toHaveCount(2);
  expect(errors).toEqual([]);
});
